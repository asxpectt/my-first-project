# Write a program that prints even numbers between 1 - 20

# Loop through numbers 1 to 20.
#
# Check if the number is even (i.e., number MOD 2 == 0).
#
# If true, print the number.

for number in range (1,21): # This is the range of numbers
    if number % 2 == 0: # If number modulus 2 = 0 then print the number
        print(f" {number} is an even number")

