# Pseudo Code
# Ask the user to enter 2 integers
# Print the square of each number entered
# Add the square of both numbers entered
# Calculate the difference of the squares (first number squared minus the second number squared

first_number = int(input("Enter your first number :"))
second_number = int(input("Enter your second number :"))
first_number_squared = first_number*first_number
second_number_squared = second_number*second_number
sum_of_both_squares = first_number_squared+second_number_squared
difference_of_squares = first_number_squared-second_number_squared
print(f"The square of first  number entered is {first_number_squared}")
print(f"The square of second number entered is {second_number_squared}")
print(f"The sum of both the squares entered is {sum_of_both_squares}")
print(f"The difference of the squares entered is {difference_of_squares}")